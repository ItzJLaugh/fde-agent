"""Generate evidence files: the real numbers behind each observation in docs/notes.md.

Run from anywhere:  uv run python -m fde_agent.evidence
Each function writes one docs/evidence/E<n>-<slug>.md file.
"""

from pathlib import Path

from fde_agent.data import DATA_DIR, load_table

EVIDENCE_DIR = DATA_DIR.parents[1] / "docs" / "evidence"


def order_status_counts() -> list[tuple[str, int, float]]:
    """(status, orders, share %) for every order_status, largest first."""
    counts = load_table("orders")["order_status"].value_counts()
    total = int(counts.sum())
    return [
        (str(status), int(n), round(100 * int(n) / total, 2))
        for status, n in counts.items()
    ]


def write_e1() -> Path:
    rows = order_status_counts()
    total = sum(n for _, n, _ in rows)
    delivered = next(n for status, n, _ in rows if status == "delivered")
    lines = [
        "# E1: Order status breakdown",
        "",
        "**Source:** `orders` table, `order_status` column · "
        "**Generated by:** `uv run python -m fde_agent.evidence`",
        "",
        "| order_status | orders | share |",
        "|---|---:|---:|",
        *[f"| {status} | {n:,} | {pct}% |" for status, n, pct in rows],
        f"| **total** | **{total:,}** | **100%** |",
        "",
        f"**Not delivered:** {total - delivered:,} orders "
        f"({100 * (total - delivered) / total:.2f}%).",
        "",
        "Used in: notes.md → DQ5, H1.",
        "",
    ]
    path = EVIDENCE_DIR / "E1-order-status.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


if __name__ == "__main__":
    print(f"wrote {write_e1()}")
